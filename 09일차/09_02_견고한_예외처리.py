import os

print("========== 1. else / finally ==========")

# ---------------------------------------------------------------------------
#   try:      위험한 코드
#   except:   실패했을 때
#   else:     예외가 '하나도 안 났을 때만'
#   finally:  성공·실패와 무관하게 '무조건 마지막에' (파일 닫기 등 뒷정리)
# ---------------------------------------------------------------------------

def parse(text):
    try:
        v = float(text)
    except ValueError:
        print("실패")
    else:
        print("성공:", v)          # 예외 없을 때만
    finally:
        print("종료")              # 무조건 실행

parse("62.5")                     # → 성공: 62.5 / 종료
print("-" * 10)
parse("abc")                      # → 실패 / 종료


print()
print("========== 2. ★핵심 패턴★ 반복문 안 try + continue ==========")

# ---------------------------------------------------------------------------
# 센서 데이터에 불량 줄이 섞여 있어도 '그 줄만 건너뛰고' 나머지는 처리한다.
# ★중요★ try는 반복문 '안'에 둔다.
#         밖에 두면 첫 불량에서 전체가 중단되어 버린다!
# ---------------------------------------------------------------------------

# 예시 데이터 준비 (ERR이라는 불량 줄이 섞여 있음)
with open("_t.txt", "w", encoding="utf-8") as f:
    f.write("70\n80\nERR\n90\n")

with open("_t.txt", "r", encoding="utf-8") as f:
    lines = f.readlines()         # 블록 밖에서 쓸 값은 안에서 담아둠
print("줄 수:", len(lines))       # → 줄 수: 4

total = 0.0
count = 0
bad = []
for i, line in enumerate(lines):
    try:
        total += float(line)      # "ERR"에서 ValueError
        count += 1
    except ValueError:
        bad.append(i)             # 불량 줄 번호 기록
        continue                  # 다음 줄로 (건너뛰기)

print("정상:", count, "불량줄:", bad)   # → 정상: 3 불량줄: [2]
if count > 0:                     # 0으로 나누기 방지
    print("평균:", round(total / count, 1))   # → 평균: 80.0


print()
print("========== 3. bare except 회피 · as e ==========")

# ---------------------------------------------------------------------------
# 나쁨:  except:            ← 모든 예외를 뭉뚱그려 잡아 '진짜 버그까지 숨김'
# 좋음:  except ValueError as e:   ← 구체적으로, e에 원인 메시지가 담김
# ---------------------------------------------------------------------------

try:
    v = float("스물")
except ValueError as e:
    print("원인:", e)             # → 원인: could not convert string to float: '스물'
# e를 출력하면 '무엇이 왜 잘못됐는지'를 알 수 있어 디버깅이 쉬워진다


print()
print("========== 4. raise ― 우리 규칙을 직접 강제 ==========")

# ---------------------------------------------------------------------------
# 파이썬이 '오류로 보지 않는' 값도, 우리 규칙에 어긋나면 직접 예외를 일으킨다.
# 형식:  raise ValueError("메시지")
#   예) 센서 온도가 -999(오류값)이면 파이썬은 그냥 숫자로 보지만,
#       우리는 "말이 안 되는 값"이므로 raise로 차단한다.
# ---------------------------------------------------------------------------

def validate(temp):
    if temp > 200 or temp < -50:
        raise ValueError("범위 밖")    # 규칙 위반 → 예외 일으키기
    return temp

print(validate(78))               # → 78   (정상)

try:
    validate(-999)                # 규칙 위반 → raise
except ValueError as e:
    print("검증 실패:", e)         # → 검증 실패: 범위 밖


print()
print("========== 5. finally로 안전하게 뒷정리 ==========")

# 파일이 열렸을 때만 닫기 (with open이 더 편하지만, finally의 원리를 이해)
f = None
try:
    f = open("_t.txt", "r", encoding="utf-8")
    data = f.readlines()
    print("읽은 줄 수:", len(data))    # → 읽은 줄 수: 4
finally:
    if f:                         # 파일이 실제로 열렸을 때만
        f.close()
        print("안전하게 닫음")     # → 안전하게 닫음


# =============================================================================
#  임시 파일 정리
# =============================================================================
if os.path.exists("_t.txt"):
    os.remove("_t.txt")


