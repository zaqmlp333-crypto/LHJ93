# -----------------------------------------------------------------------------
#  Q1.  else와 finally의 차이는?
#       A. else는 예외가 안 났을 때만, finally는 성공·실패 무관하게 무조건 실행.
#
#  Q2.  반복문에서 불량 줄만 건너뛰려면 try를 어디에 둬야 하나?
#       A. 반복문 '안'에. 밖에 두면 첫 불량에서 전체 반복이 중단된다.
#
#  Q3.  continue는 여기서 무슨 역할인가?
#       A. 불량 줄을 만나면 나머지를 건너뛰고 다음 줄로 넘어간다.
#
#  Q4.  except: 만 쓰는 게 왜 나쁜가?
#       A. 모든 예외를 뭉뚱그려 잡아 진짜 버그까지 숨긴다. 구체적으로 잡아야 한다.
#
#  Q5.  except ValueError as e 의 e는 무엇인가?
#       A. 오류의 원인 메시지. 출력하면 무엇이 왜 잘못됐는지 알 수 있다.
#
#  Q6.  raise는 언제 쓰나?
#       A. 파이썬이 오류로 안 보는 값이라도, 우리 규칙에 어긋나면 직접 예외를 일으킬 때.
#          (예: -999 같은 센서 오류값 차단)
