print("========== 2. try-except 기본 구조 ==========")

# ---------------------------------------------------------------------------
# 형식:
#     try:
#         위험한 코드          ← 오류가 날 수 있는 코드
#     except:
#         문제 생기면 할 일     ← 오류가 나면 여기로 점프 (멈추지 않고 계속!)
# ---------------------------------------------------------------------------

try:
    temp = int("스물")             # ValueError 발생!
except:
    print("못 바꿈")               # → 못 바꿈   (except로 점프)
print("계속 진행")                 # → 계속 진행   (프로그램이 안 멈춤!)

# 원칙: try에는 위험한 코드만 '작게', 예외는 '구체적으로' 잡는다 (아래)


print()
print("========== 3. 구체적 예외 ― ValueError vs TypeError ==========")

# ---------------------------------------------------------------------------
#   ValueError : 종류는 맞지만 '내용'이 부적절   int("3.5")  "3.5"는 정수로 못 바꿈
#   TypeError  : 값의 '종류' 자체가 틀림          10 + "개"   숫자 + 글자
# ---------------------------------------------------------------------------

try:
    n = int("3.5")                # ValueError
except ValueError:
    print("정수로 못 바꿈")         # → 정수로 못 바꿈

try:
    x = 10 + "개"                 # TypeError
except TypeError:
    print("종류가 안 맞음")         # → 종류가 안 맞음


print()
print("========== 4. 여러 예외 동시 처리 ==========")

# ---------------------------------------------------------------------------
# except를 여러 개 두면 오류 종류마다 다르게 대처할 수 있다.
# 함수와 함께 쓰면 "실패해도 대체값을 돌려주는" 안전한 함수가 된다.
# ---------------------------------------------------------------------------

def to_int(value):
    try:
        return int(value)
    except ValueError:             # 글자 → 숫자 실패
        return "숫자 아님"
    except TypeError:              # 종류 자체가 틀림
        return "종류 오류"

print(to_int("62"))               # → 62
print(to_int("스물"))             # → 숫자 아님
print(to_int(None))               # → 종류 오류

# 묶어 쓰기: except (ValueError, TypeError): 처럼 괄호로 묶어 한 번에 처리 가능


print()
