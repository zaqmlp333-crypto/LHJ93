# ZeroDivisionError : 0으로 나눔
def divide(a, b):
    try:
        return a / b
    except ZeroDivisionError:
        return "0으로 못 나눔"
print(divide(10, 0))              # → 0으로 못 나눔
print(divide(20, 4))              # → 5.0

# ValueError : 입력 검증
def parse(text):
    try:
        return float(text)
    except ValueError:
        return "숫자 아님"
print(parse("62.5"))              # → 62.5
print(parse("덥다"))              # → 숫자 아님

# IndexError : 리스트 범위 밖
def get(lst, i):
    try:
        return lst[i]
    except IndexError:
        return "범위 밖"
print(get([1, 2, 3], 5))          # → 범위 밖
print(get([1, 2, 3], 0))          # → 1


