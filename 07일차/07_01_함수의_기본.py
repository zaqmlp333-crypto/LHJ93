print("========== 1. 함수란 ― 코드에 이름 붙이기 ==========")

# ---------------------------------------------------------------------------
# 함수 = 자주 쓰는 코드에 '이름'을 붙여 두고, 그 이름으로 언제든 다시 부르는 것.
#
# 형식:
#     def 함수이름():          ← def로 정의, 끝에 콜론(:)
#         실행할 코드           ← 들여쓰기(4칸) = 함수에 속한 코드
#
#   실수: def 줄 콜론 누락 → SyntaxError / 본문 들여쓰기 누락 → IndentationError
# ---------------------------------------------------------------------------

def greet():
    print("점검을 시작합니다")

# 위는 '만들어 두기'일 뿐 — 아직 아무것도 출력 안 됨!


print("========== 2. ★핵심★ 정의만으로는 실행 안 된다 → 호출 ==========")

# 이름 뒤에 괄호를 붙여 '호출'해야 비로소 실행된다
greet()                           # → 점검을 시작합니다
greet()                           # → 점검을 시작합니다   (부른 만큼 실행)

# ★가장 흔한 '출력 없음' 원인★ = 정의만 하고 호출을 안 함!


print()
print("========== 3. 함수 안 / 밖 ― 들여쓰기가 경계 ==========")

def demo():
    print("함수 안 (들여쓰기)")     # 함수에 속함 → 호출할 때만 실행
print("함수 밖")                   # → 함수 밖   (들여쓰기 밖 → 바로 실행)
demo()                            # → 함수 안 (들여쓰기)


print()
print("========== 4. 정의가 먼저, 호출이 나중 ==========")

# 정의보다 호출이 위에 있으면 NameError (아직 만들어지기 전이라)
#   hi()          → NameError: name 'hi' is not defined
#   def hi(): ...
# 반드시 '정의 먼저 → 호출 나중' 순서.

def hi():
    print("안녕하세요")
hi()                              # → 안녕하세요   (정의 다음에 호출 — OK)


print()
print("========== 5. 함수 이름 규칙 (변수 이름과 동일) ==========")

# ---------------------------------------------------------------------------
# 규칙: 영문·숫자·밑줄, 숫자로 시작 불가, 공백 불가 (변수와 같음)
# 좋은 이름: 무슨 일을 하는지 드러나게 (보통 동사 + 구체적 대상)
#   실수: def 2nd_check():  (숫자 시작) / def check temp():  (공백) → SyntaxError
# ---------------------------------------------------------------------------

def check_temperature():          # 좋은 이름 (동사+대상, snake_case)
    print("온도 확인")
check_temperature()               # → 온도 확인


print()
print("========== 6. ★가장 중요한 이유★ 코드 중복 → 함수로 묶기 ==========")

# ---------------------------------------------------------------------------
# 같은 여러 줄이 반복되면 → 함수 하나로 묶고, 그 자리를 '호출'로 바꾼다.
# 장점: 코드가 짧아지고, 고칠 때 '한 곳만' 고치면 된다.
# ---------------------------------------------------------------------------

# 함수로 묶기 전이라면 아래 3줄을 설비마다 반복해서 써야 했다:
#   print("점검을 시작합니다")
#   print("안전 장비를 확인하세요")
#   print("기록을 준비하세요")

def start_check():                # 3줄을 함수 하나로 묶음
    print("점검을 시작합니다")
    print("안전 장비를 확인하세요")
    print("기록을 준비하세요")

start_check()                     # 압축기A 점검  (호출 한 줄로 끝!)
print("-" * 10)
start_check()                     # 펌프1 점검


print()
print("========== 7. 종합 : 여러 함수 조합 ==========")

def line():
    print("=" * 20)

def check():
    print("점검을 시작합니다")
    print("기록을 준비하세요")

line()                            # → ====================
check()                           # → 점검을 시작합니다 / 기록을 준비하세요
line()                            # → ====================
check()
# 필요한 함수들을 만들어 두고 순서대로 호출 = 프로그램 조립


