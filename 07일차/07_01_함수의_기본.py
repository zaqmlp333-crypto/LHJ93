#            코드 중복을 함수로 묶기(리팩토링), 여러 번 호출
#  ※ 이 단원은 '인자 없는 함수'만. 매개변수·반환값은 07_02에서.
#  사용법  : "→" 결과를 먼저 예상한 뒤 실행해서 맞춰보기
