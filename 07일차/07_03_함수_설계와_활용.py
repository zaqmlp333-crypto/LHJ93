print("========== 5. docstring ― 함수 설명 달기 ==========")

# 정의 다음 줄에 삼중 따옴표로 설명을 달면 다른 사람(과 미래의 나)이 쓰기 쉽다
def get_avg(values):
    """숫자 목록을 받아 평균을 돌려준다."""    # docstring
    return sum(values) / len(values)

print(get_avg([10, 20, 30]))      # → 20.0
print(get_avg.__doc__)            # → 숫자 목록을 받아 평균을 돌려준다.


