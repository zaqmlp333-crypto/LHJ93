print("========== 2. 지역변수와 범위(스코프) ==========")

# ---------------------------------------------------------------------------
# 함수 안에서 만든 변수는 '그 함수 안에서만' 유효하다 = 지역변수.
# → 함수끼리 같은 이름을 써도 서로 충돌하지 않는 안전장치.
# 밖에서 쓰려면 return으로 내보내야 한다.
# ---------------------------------------------------------------------------

def calc():
    result = 10 + 5               # result는 지역변수
    return result                 # 밖에서 쓰려면 return

print(calc())                     # → 15
# print(result)                   → NameError: 함수 밖에서는 지역변수를 못 봄!

# 함수 안 대입은 바깥 변수에 영향 없음
x = 10
def change():
    x = 20                        # 이 x는 함수 안 x (바깥과 별개)
change()
print(x)                          # → 10   (바깥 x는 그대로!)


