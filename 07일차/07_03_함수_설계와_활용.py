print("========== 3. 입력-처리-출력 설계 ― 한 함수 = 한 기능 ==========")

# ---------------------------------------------------------------------------
# 큰 작업을 작은 함수로 나누고(한 함수는 한 가지 일만), 결과를 이어 넘긴다.
# → 읽기 쉽고, 고치기 쉽고, 재사용하기 쉽다.
# ---------------------------------------------------------------------------

def get_average(values):          # 처리 1: 평균 구하기
    return sum(values) / len(values)

def judge(avg, limit=80):         # 처리 2: 판정하기
    if avg > limit:
        return "위험"
    else:
        return "정상"

temps = [75, 88, 91]
avg = get_average(temps)          # 중간 결과를 변수에 담아
print(round(avg, 1), judge(avg))  # → 84.7 위험   (이어서 판정)


