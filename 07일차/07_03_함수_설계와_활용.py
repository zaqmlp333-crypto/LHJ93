print("========== 1. 기본값 인자 ― 자주 쓰는 값 미리 지정 ==========")

# ---------------------------------------------------------------------------
# 형식:  def 함수(필수, 선택=기본값):  ...
#   · 인자를 생략하면 기본값 사용, 넣으면 그 값으로 덮어씀
#   · 거의 항상 같은 값을 매번 적는 번거로움을 줄인다
#   ★규칙★ 기본값 없는 매개변수가 앞, 있는 것이 뒤
#           def f(a=0, b):  → SyntaxError
# ---------------------------------------------------------------------------

def report(name, value, unit="도"):
    print(name + ": " + str(value) + unit)

report("압축기A", 75.3)           # → 압축기A: 75.3도   (unit 생략 → 기본값 "도")
report("펌프1", 7.2, "bar")       # → 펌프1: 7.2bar     ("bar"로 덮어쓰기)

# 판정 함수에 기본 임계값
def status(temp, limit=90):
    if temp > limit:
        print("경고")
    else:
        print("정상")

status(78)                        # → 정상   (limit 기본값 90)
status(95)                        # → 경고
status(50, limit=40)             # → 경고   (기본값 덮어쓰기)


