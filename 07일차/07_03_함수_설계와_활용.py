print("========== 4. 함수 조합 (파이프라인) ==========")

# 함수의 결과를 다음 함수로 넘기며 처리 흐름을 만든다
def average(a, b):
    return (a + b) / 2

def check(value):
    if value > 90:
        return "경고"
    else:
        return "정상"

avg = average(80, 90)             # 처리 결과 85.0
print(check(avg))                 # → 정상   (이어서 판정)

# 센서 분석 함수 세트
def calc_avg(values):
    return sum(values) / len(values)

def get_status(avg, limit=90):
    if avg > limit:
        return "경고"
    else:
        return "정상"

result = calc_avg([78, 92, 85])
print(result, get_status(result))  # → 85.0 정상


