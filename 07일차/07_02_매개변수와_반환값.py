print("========== 1. 매개변수와 인자 ― 값을 받는 함수 ==========")

# ---------------------------------------------------------------------------
# 같은 함수를 '값만 바꿔' 재사용하기 위해 값을 받는다.
#   매개변수 = 정의할 때 () 안의 '받을 변수'
#   인자     = 호출할 때 () 안에 '넣는 값'
#
# 형식:  def 함수(매개변수):  ...      호출:  함수(인자)
# ---------------------------------------------------------------------------

def check(name):                  # name = 매개변수
    print(name + " 점검을 시작합니다")

check("압축기A")                  # → 압축기A 점검을 시작합니다   ("압축기A" = 인자)
check("펌프1")                    # → 펌프1 점검을 시작합니다     (같은 함수, 다른 값)

# 실수: check()  → 인자 부족 (missing 1 required positional argument)


