print("========== 2. 여러 매개변수 ― 순서가 중요 ==========")

# 위치 인자는 '순서대로' 매개변수에 들어간다
def report(name, temp):
    print(name + "의 온도: " + str(temp) + "도")

report("압축기A", 75.3)           # → 압축기A의 온도: 75.3도   (name←압축기A, temp←75.3)

# ★함정★ 순서를 바꾸면 '조용히' 틀린 결과 (오류도 안 남!)
# report(75.3, "압축기A")         → name에 75.3, temp에 "압축기A"가 들어가 이상해짐


print()
print("========== 3. 키워드 인자 ― 이름으로 자리 지정 ==========")

# 이름을 지정하면 순서를 몰라도 안전하고, 읽기도 쉽다
def report2(name, temp):
    print(name + ": " + str(temp))

report2(temp=75.3, name="압축기A")    # → 압축기A: 75.3   (이름 지정이라 순서 무관)
report2("펌프1", temp=92)             # → 펌프1: 92       (위치 먼저, 키워드 나중)
# 실수: 위치 인자가 키워드 뒤에 오면 에러 → f(a=3, 4) 는 X


print()
print("========== 4. ★가장 중요★ return vs print ==========")

# ---------------------------------------------------------------------------
#   print : 사람에게 '보여줄' 뿐 — 값이 남지 않는다
#   return: 값을 프로그램에 '돌려줘서' 이어 쓸 수 있다
# ---------------------------------------------------------------------------

def add(a, b):
    return a + b                  # 값을 돌려줌

total = add(3, 4)                 # 돌려받아 변수에 담기
print(total)                      # → 7
print(total * 10)                 # → 70   (돌려받은 값을 '이어 쓸 수' 있다!)

# print만 하는 함수와 비교
def add_print(a, b):
    print(a + b)                  # 보여주기만 함

x = add_print(3, 4)               # → 7 (출력은 됨)
print(x)                          # → None   (돌려준 게 없어서 담을 값이 없다!)

# ★엣지★ return을 만나면 함수가 '즉시 종료' → 그 아래 코드는 실행 안 됨
def demo():
    return 1
    print("이 줄은 실행되지 않음")   # return 아래라 무시됨
print(demo())                     # → 1


