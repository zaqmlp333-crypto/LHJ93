print("========== 5. 반환값을 이어서 활용 ==========")

def calc_avg(a, b):
    return (a + b) / 2

avg = calc_avg(80, 90)
print(avg)                        # → 85.0
print(avg + 5)                    # → 90.0   (담은 값을 계속 활용)


print()
print("========== 6. 여러 값 반환 · 언패킹 ==========")

# 쉼표로 여러 값을 return하면 튜플로 묶여 돌아온다 → 언패킹으로 나눠 받기
def min_max(values):
    return min(values), max(values)    # 두 값을 돌려줌

low, high = min_max([75.3, 88.0, 49.1])   # 언패킹
print(low, high)                  # → 49.1 88.0

# 세 값도 한 번에 (min, max, 평균)
def stats(v):
    return min(v), max(v), sum(v) / len(v)

lo, hi, avg = stats([78, 92, 85])
print(lo, hi, avg)                # → 78 92 85.0

# 참고: min/max/sum/len 은 파이썬 내장 함수 (직접 안 만들어도 됨)


print()
print("========== 7. None ― 반환이 없는 함수의 결과 ==========")

# return이 없는 함수는 None(값 없음)을 돌려준다
def just_print(x):
    print(x)                      # print만 하고 return 없음

result = just_print("안녕")        # → 안녕
print(result)                     # → None
# "함수 결과를 담았는데 None이 나온다" = 그 함수에 return이 없다는 신호!


