print("=" * 12, "PART 2. 셋으로 비교", "=" * 12)

# ---------------------------------------------------------------------------
# 셋 = 중괄호로 만든 집합. 두 가지 특징:
#   ① 무중복 — 같은 값을 넣어도 하나만 유지 (종류만 따짐)
#   ② 무순서 — 순서가 없어 인덱스로 못 꺼냄
# 만드는 법: {값, 값} 또는 리스트를 set()으로 감싸기
# ★함정★ 빈 중괄호 {} 는 딕셔너리! 빈 셋은 반드시 set()
# ---------------------------------------------------------------------------

ids = {"S01", "S02", "S01"}            # S01이 중복
print(ids)                             # → {'S01', 'S02'}   (하나만 남음, 순서는 다를 수 있음)

logs = ["S01", "S02", "S01", "S03"]
unique = set(logs)                     # 리스트를 set으로 → 중복 제거
print(sorted(unique))                  # → ['S01', 'S02', 'S03']   (정렬해서 보기)
print(len(unique))                     # → 3   (종류 수)


print()
print("========== 8. add · in ==========")

alerts = {"S01", "S02"}
alerts.add("S03")                      # 리스트의 append 같지만 중복은 무시
alerts.add("S01")                      # 이미 있으니 변화 없음 (오류도 안 남)
print(sorted(alerts))                  # → ['S01', 'S02', 'S03']

# in: 포함 여부 (셋은 리스트보다 훨씬 빠르게 찾음)
print("S02" in alerts)                 # → True
print("S09" in alerts)                 # → False


