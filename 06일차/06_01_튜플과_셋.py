print("========== 7. 중첩 튜플 · enumerate · sorted ==========")

# 튜플 안에 튜플 (위치 좌표 같은 부가 정보)
sensor = ("모터온도", 78, (3, 5))
print(sensor[2])                       # → (3, 5)   안쪽 튜플
print(sensor[2][0])                    # → 3        인덱스 두 번

# enumerate: 번호와 값을 동시에 (번호 세는 변수 불필요)
sensors = [("모터온도", 78), ("진동", 0.5)]
for i, s in enumerate(sensors, 1):     # 시작값 1 → 번호를 1부터
    print(i, s[0])                     # → 1 모터온도 / 2 진동

# sorted: 정렬 (정렬 기준을 맨 앞에 두면 그 값 기준)
data = [(78, "모터온도"), (95, "베어링진동"), (32, "펌프압력")]
hot = sorted(data, reverse=True)       # 값이 앞이라 값 기준, reverse=큰 값부터
print(hot[0])                          # → (95, '베어링진동')   가장 높은 센서


