print("========== 6. ★핵심 형태★ 튜플 리스트 + 반복문 언패킹 ==========")

# ---------------------------------------------------------------------------
# 실무에서 가장 많이 쓰는 형태: 큰 리스트[ ] 안에 작은 튜플( )들
#   · 각 센서는 튜플로 묶어 짝 보호,  전체는 리스트로 자유롭게 관리
#   · for 에 변수 두 개로 받으면 반복마다 '언패킹까지 한 번에'
# ---------------------------------------------------------------------------

sensors = [
    ("모터온도", 78),
    ("회전속도", 1750),
    ("펌프압력", 95),
]
print(len(sensors))                    # → 3   (센서 개수)

for name, value in sensors:            # 반복마다 이름·값 자동 분리
    print(name, value)
# → 모터온도 78 / 회전속도 1750 / 펌프압력 95

# 반복 + 언패킹 + 조건문 = 기준 초과 검사
for name, value in sensors:
    if value > 90:
        print(name, "경고")            # → 회전속도 경고 / 펌프압력 경고
# 센서가 3개든 300개든 코드는 그대로 — 이게 반복문의 힘


