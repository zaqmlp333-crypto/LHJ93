print("=" * 12, "PART 1. 튜플로 묶기", "=" * 12)

# ---------------------------------------------------------------------------
# 튜플 = 소괄호로 값을 묶은 것. 리스트와 비슷하지만 '한 번 만들면 못 바꾼다(불변)'.
#   · 이름과 값처럼 '짝지어 다니는 데이터'를 하나로 묶어 순서가 어긋나지 않게 보호
#   · 리스트는 대괄호 [ ], 튜플은 소괄호 ( )
# ---------------------------------------------------------------------------

sensor = ("모터온도", 78)
print(sensor)                          # → ('모터온도', 78)

# ★함정★ 값이 하나뿐인 튜플은 뒤에 쉼표가 필수!
one = (78,)
not_tuple = (78)                       # 쉼표가 없으면 그냥 계산용 괄호 = 숫자
print(type(one))                       # → <class 'tuple'>
print(type(not_tuple))                 # → <class 'int'>


