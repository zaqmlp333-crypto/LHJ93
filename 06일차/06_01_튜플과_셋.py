print("========== 9. 집합 연산 ― 두 목록 비교의 핵심 ==========")

# ---------------------------------------------------------------------------
#   union(합집합)        A | B    합친 전체        → 종류 파악
#   intersection(교집합)  A & B    공통인 것        → 공통점 찾기
#   difference(차집합)    A - B    한쪽만           → 변화 추적
# ---------------------------------------------------------------------------

line_a = {"S01", "S02", "S03"}
line_b = {"S03", "S04"}

print(sorted(line_a.union(line_b)))          # → ['S01', 'S02', 'S03', 'S04']  전체(S03 한 번만)
print(sorted(line_a.intersection(line_b)))   # → ['S03']              공통
print(sorted(line_a.difference(line_b)))     # → ['S01', 'S02']       A에만
print(sorted(line_b.difference(line_a)))     # → ['S04']              B에만
# ★주의★ 차집합은 방향에 따라 결과가 다르다 (A-B ≠ B-A)

# 활용: 어제/오늘 이상 센서 비교
yesterday = {"S01", "S02", "S03"}
today = {"S02", "S03", "S05"}
print("신규 이상:", sorted(today.difference(yesterday)))     # → ['S05']         오늘 새로 생김
print("지속 이상:", sorted(today.intersection(yesterday)))   # → ['S02', 'S03']  이틀 연속


