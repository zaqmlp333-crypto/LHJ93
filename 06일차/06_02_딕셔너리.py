#            순회(keys·values·items) · update · zip · 중첩 딕셔너리,
#            튜플·셋·딕셔너리 선택 기준
#  큰 그림 : 묶는 튜플 · 거르는 셋 · '찾는 딕셔너리'
#  사용법  : "→" 결과를 먼저 예상한 뒤 실행해서 맞춰보기
# =============================================================================

print("=" * 12, "PART 1. 딕셔너리 기초", "=" * 12)

# ---------------------------------------------------------------------------
# 딕셔너리 = 순서 번호 대신 '이름표(키)'로 값을 찾는 자료구조.
#   · 사전에서 단어(키)를 찾으면 뜻(값)이 나오듯
#   · 리스트는 위치가 밀리면 번호가 어긋나지만, 딕셔너리는 이름만 알면 항상 정확
#   · 실무에서 가장 많이 쓰는 자료구조
#
# 문법:  { 키 : 값 , 키 : 값 }     ← 콜론(:)으로 짝지음
#   · 콜론이 있으면 딕셔너리, 없으면 셋
#   · 빈 중괄호 {} 는 '빈 딕셔너리' (빈 셋은 set())
# ---------------------------------------------------------------------------

sensors = {"모터온도": 78, "진동": 0.5}
print(sensors)                         # → {'모터온도': 78, '진동': 0.5}
print(type(sensors))                   # → <class 'dict'>


print()
print("========== 2. 키로 값 꺼내기 ==========")

sensors = {"모터온도": 78, "진동": 0.5}
print(sensors["모터온도"])              # → 78   (번호 자리에 이름표)
print(sensors["진동"])                  # → 0.5
# print(sensors["유량"])               → KeyError: 없는 키는 오류 (아래 get으로 해결)


print()
print("========== 3. 추가 · 수정 · 삭제 ==========")

# ---------------------------------------------------------------------------
# 추가/수정: 딕셔너리[키] = 값   (같은 문법! 키가 없으면 추가, 있으면 수정)
# 삭제:      del 딕셔너리[키]
# ---------------------------------------------------------------------------

sensors = {"모터온도": 78}
sensors["펌프압력"] = 95               # 없는 키 → 추가
sensors["유량"] = 42                   # 추가
print(sensors)                         # → {'모터온도': 78, '펌프압력': 95, '유량': 42}

sensors["모터온도"] = 80               # 있는 키 → 수정
del sensors["펌프압력"]                # 삭제
print(sensors)                         # → {'모터온도': 80, '유량': 42}


print()
print("========== 4. get ― 없는 키도 안전하게 ==========")

# 딕셔너리.get(키, 기본값) : 키가 없어도 오류 대신 기본값을 돌려줌
sensors = {"모터온도": 78}
print(sensors.get("모터온도"))          # → 78
print(sensors.get("유량"))             # → None    (없으면 None, 오류 아님)
print(sensors.get("유량", 0))          # → 0       (기본값 지정)
# 어떤 설비엔 유량 센서가 있고 없고 — 빠진 센서를 0으로 처리해 계산이 안 멈추게


print()
print("========== 5. in ― 키 존재 확인 (값이 아니라 키!) ==========")

sensors = {"모터온도": 78, "펌프압력": 95}
print("모터온도" in sensors)            # → True    (키를 봄)
print(78 in sensors)                   # → False   (78은 '값'이라 False!)

if "유량" in sensors:                  # 꺼내기 전에 확인하면 오류 방지
    print(sensors["유량"])
else:
    print("유량 센서 없음")             # → 유량 센서 없음

# 참고: 키가 될 수 있는 것 = 안 바뀌는 값 (문자열·숫자·튜플 O / 리스트 X)


print()
print("=" * 12, "PART 2. 순회와 갱신", "=" * 12)

# ---------------------------------------------------------------------------
#   keys()   → 키(이름)만        이름 목록이 필요할 때
#   values() → 값만              합계·평균 등 통계
#   items()  → 키와 값 함께      ★가장 많이 씀★ (이름과 값을 같이 다룰 때)
# ---------------------------------------------------------------------------

sensors = {"모터온도": 78, "압력": 95}
print(list(sensors.keys()))            # → ['모터온도', '압력']
print(list(sensors.values()))          # → [78, 95]

# values로 평균 (sum과 len 조합)
avg = sum(sensors.values()) / len(sensors)
print(avg)                             # → 86.5

# items로 키·값 동시 순회 (튜플 언패킹과 같은 패턴!)
for name, value in sensors.items():
    print(name, "측정값:", value)
# → 모터온도 측정값: 78 / 압력 측정값: 95

print(len(sensors))                    # → 2   (키-값 쌍 개수 = 센서 수)


print()
print("========== 6. items + 조건 ― 임계값 비교 (이상 감지의 기본형) ==========")

# 같은 센서 이름을 '다리' 삼아 두 딕셔너리(측정값·임계값)를 연결
values = {"모터온도": 95, "압력": 88}
limits = {"모터온도": 90, "압력": 90}
for name, value in values.items():
    if value > limits[name]:           # 같은 이름의 임계값과 비교
        print(name, "경고")            # → 모터온도 경고   (95>90, 압력 88≤90은 통과)


print()
print("========== 7. update ― 여러 값 한 번에 갱신/추가 ==========")

sensors = {"모터온도": 78, "진동": 0.5}
new_data = {"모터온도": 80, "유량": 42}
sensors.update(new_data)               # 있으면 갱신(모터온도), 없으면 추가(유량)
print(sensors)                         # → {'모터온도': 80, '진동': 0.5, '유량': 42}
# 센서 50개가 한꺼번에 들어와도 한 줄로 반영


print()
print("========== 8. zip ― 두 리스트를 딕셔너리로 ==========")

# dict(zip(이름들, 값들)) : 지퍼처럼 앞에서부터 하나씩 짝지음
names = ["모터온도", "진동", "압력"]
values = [78, 0.5, 95]
sensors = dict(zip(names, values))
print(sensors)                         # → {'모터온도': 78, '진동': 0.5, '압력': 95}
# ★주의★ 두 리스트의 순서가 정확히 맞아야 함


print()
print("========== 9. 값에 리스트/딕셔너리 담기 (중첩) ==========")

# 값에 리스트 → 한 센서의 여러 측정 이력
sensors = {"모터온도": [78, 79, 80]}
temps = sensors["모터온도"]
print(sum(temps) / len(temps))         # → 79.0   (평균)
print(max(temps))                      # → 80     (최고값)

# 값에 딕셔너리 → 여러 설비를 체계적으로 관리 (키를 두 번!)
plant = {
    "1번모터": {"온도": 78, "상태": "정상"},
    "2번펌프": {"압력": 95, "상태": "경고"},
}
print(plant["2번펌프"]["압력"])         # → 95   (바깥 키 → 안쪽 키)

for name, info in plant.items():
    if info["상태"] == "경고":
        print(name, "점검 필요")        # → 2번펌프 점검 필요


print()
print("========== 10. 표 데이터 → 딕셔너리 (split 활용) ==========")

# "센서명,값" 형태의 행들을 딕셔너리로 (03_05 split 복습)
rows = ["온도,78", "압력,95", "진동,0.5"]
sensors = {}
for row in rows:
    name, value = row.split(",")       # 쉼표로 나눠 언패킹
    sensors[name] = float(value)       # 값은 숫자로 변환해서 저장
print(sensors)                         # → {'온도': 78.0, '압력': 95.0, '진동': 0.5}


